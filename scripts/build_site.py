#!/usr/bin/env python3
"""Validate and stage public pages; legacy redirect files exist only in dist."""

import argparse
import html
import json
from pathlib import Path
import posixpath
import shutil
from urllib.parse import quote

from build_index import build_index, load_catalog
from site_utils import aliases, check_links


MARKER = ".notes-site-build"


def redirect_page(alias, target, catalog):
    """Keep old share links usable, including their query and fragment state."""
    relative = quote(posixpath.relpath(target, posixpath.dirname(alias) or "."))
    canonical = catalog["site_url"] + quote(target)
    return ("""<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>文章已迁移 · 技术笔记</title>
""" + f'<link rel="canonical" href="{html.escape(canonical, quote=True)}">\n'
            + f'<meta http-equiv="refresh" content="0; url={html.escape(relative, quote=True)}">\n'
            + "<script>const target=new URL(" + json.dumps(relative) + ",location.href);"
            + "target.search=location.search;target.hash=location.hash;location.replace(target.href);</script>\n"
            + '</head><body><p>文章已整理到新目录：<a href="'
            + html.escape(relative, quote=True) + '">继续阅读</a>。</p></body></html>\n')


def build_site(repo, output=None):
    """Copy explicit public inputs and refuse to remove an unowned directory."""
    repo = repo.resolve()
    output = output or repo / "dist"
    if (output.is_symlink() or output.resolve() == repo
            or (output.resolve().is_relative_to(repo) and output.resolve() != repo / "dist")):
        raise ValueError("Output must be dist/ or a dedicated directory outside the repository")
    catalog = load_catalog(repo)
    build_index(repo)
    pages = ["index.html", *[a["file"] for a in catalog["articles"]]]
    check_links(repo, pages, catalog["site_url"])
    if output.exists():
        if not (output / MARKER).is_file():
            raise ValueError(f"Output is not owned by this builder: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("Generated by scripts/build_site.py\n", encoding="utf-8")
    for name in [*pages, "catalog.json", *catalog["resources"]]:
        source, target = repo / name, output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if source.is_dir():
            shutil.copytree(source, target)
        else:
            shutil.copy2(source, target)
    for alias, target in aliases(catalog).items():
        path = output / alias
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(redirect_page(alias, target, catalog), encoding="utf-8")
    (output / ".nojekyll").touch()
    check_links(output, [*pages, *aliases(catalog)], catalog["site_url"])
    return catalog


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Dedicated build output; defaults to dist/")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    catalog = build_site(root, args.output)
    print(f"Built {len(catalog['articles'])} articles and {len(aliases(catalog))} legacy redirects")
